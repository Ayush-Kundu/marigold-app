// The only bridge between Marigold's pages and the Mac app. Pages can ask for a Touch ID
// approval, open the main window, and receive sign-in handoffs — nothing else.
const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("marigoldApp", {
  isApp: true,
  retryEngine: () => ipcRenderer.invoke("engine-retry"),
  showLog: () => ipcRenderer.invoke("show-log"),
  info: () => ipcRenderer.invoke("app-info"),
  touchID: (stepId, reason) => ipcRenderer.invoke("touch-id", { stepId, reason }),
  testTouchID: () => ipcRenderer.invoke("touch-id", { test: true, reason: "test Touch ID for Marigold" }),
  openMain: (chatId) => ipcRenderer.invoke("open-main", chatId),
  hideQuick: () => ipcRenderer.invoke("hide-quick"),
  showPermissions: () => ipcRenderer.invoke("show-permissions"),
  permissions: () => ipcRenderer.invoke("permissions"),
  requestPermission: (kind) => ipcRenderer.invoke("request-permission", kind),
  notifyStatus: () => ipcRenderer.invoke("notify-status"),
  openNotifySettings: () => ipcRenderer.invoke("notify-settings"),
  micAccess: () => ipcRenderer.invoke("mic-access"),
  openMicSettings: () => ipcRenderer.invoke("mic-settings"),
  onAskTab: (cb) => { const f = (_e, q, deep) => cb(q, !!deep); ipcRenderer.on("ask-tab", f); return () => ipcRenderer.off("ask-tab", f); },
  onDeepDive: (cb) => { const f = (_e, q) => cb(q); ipcRenderer.on("deep-dive", f); return () => ipcRenderer.off("deep-dive", f); },
  pickFolder: () => ipcRenderer.invoke("pick-folder"),
  convState: (p) => ipcRenderer.send("conv-state", p),
  onConverse: (cb) => { const f = () => cb(); ipcRenderer.on("converse-toggle", f); return () => ipcRenderer.off("converse-toggle", f); },
  onDictate: (cb) => { const f = () => cb(); ipcRenderer.on("dictate-toggle", f); return () => ipcRenderer.off("dictate-toggle", f); },
  // Marigold Browser (tabs live in the main process; this page draws the chrome around them).
  browser: {
    state: () => ipcRenderer.invoke("browser:state"),
    host: (h) => ipcRenderer.invoke("browser:host", h),
    freeze: () => ipcRenderer.invoke("browser:freeze"),
    preconnect: (u) => ipcRenderer.invoke("browser:preconnect", u),
    snapshot: () => ipcRenderer.invoke("browser:snapshot"),
    newTab: (url) => ipcRenderer.invoke("browser:new", url),
    close: (id) => ipcRenderer.invoke("browser:close", id),
    activate: (id) => ipcRenderer.invoke("browser:activate", id),
    moveTab: (id, to) => ipcRenderer.invoke("browser:move", id, to),
    shown: (v) => ipcRenderer.invoke("browser:shown", v),
    tabMenu: (id) => ipcRenderer.invoke("browser:tab-menu", id),
    pin: (id) => ipcRenderer.invoke("browser:pin", id),
    setEngine: (id) => ipcRenderer.invoke("browser:engine-set", id),
    historyList: (q) => ipcRenderer.invoke("browser:history-list", q),
    historyDelete: (arg) => ipcRenderer.invoke("browser:history-delete", arg),
    clearData: (opts) => ipcRenderer.invoke("browser:clear-data", opts),
    download: (id, action) => ipcRenderer.invoke("browser:download", { id, action }),
    zoom: (opts) => ipcRenderer.invoke("browser:zoom", opts ?? {}),
    devtools: () => ipcRenderer.invoke("browser:devtools"),
    print: () => ipcRenderer.invoke("browser:print"),
    pageLinks: (id) => ipcRenderer.invoke("browser:page-links", id),
    onPanel: (cb) => { const f = (_e, p) => cb(p); ipcRenderer.on("browser-open-panel", f); return () => ipcRenderer.off("browser-open-panel", f); },
    onBookmarksChanged: (cb) => { const f = () => cb(); ipcRenderer.on("browser-bookmarks-changed", f); return () => ipcRenderer.off("browser-bookmarks-changed", f); },
    reopenTab: () => ipcRenderer.invoke("browser:reopen"),
    navigate: (id, input) => ipcRenderer.invoke("browser:navigate", { id, input }),
    nav: (id, what) => ipcRenderer.invoke("browser:nav", { id, what }),
    pageText: (id) => ipcRenderer.invoke("browser:page-text", id),
    pageShot: (id) => ipcRenderer.invoke("browser:page-shot", id),
    captions: (id) => ipcRenderer.invoke("browser:captions", id),
    captionsOn: (id) => ipcRenderer.invoke("browser:captions-on", id),
    revealDownload: () => ipcRenderer.invoke("browser:reveal-download"),
    suggest: (q) => ipcRenderer.invoke("browser:suggest", q),
    homeData: () => ipcRenderer.invoke("browser:home-data"),
    importSources: () => ipcRenderer.invoke("browser:import-sources"),
    importFrom: (opts) => ipcRenderer.invoke("browser:import", opts),
    reloadAll: () => ipcRenderer.invoke("browser:reload-all"),
    setProfile: (key) => ipcRenderer.invoke("browser:profile", key),
    extensions: () => ipcRenderer.invoke("browser:extensions"),
    adblock: (on) => ipcRenderer.invoke("browser:adblock", on),
    openExtension: (id) => ipcRenderer.invoke("browser:extension-open", id),
    removeExtension: (id) => ipcRenderer.invoke("browser:extension-remove", id),
    enableExtension: (id) => ipcRenderer.invoke("browser:extension-enable", id),
    bookmarks: () => ipcRenderer.invoke("browser:bookmarks"),
    toggleBookmark: (url, title) => ipcRenderer.invoke("browser:bookmark-toggle", { url, title }),
    answerPermission: (id, allow) => ipcRenderer.invoke("browser:perm", { id, allow }),
    resetPermissions: () => ipcRenderer.invoke("browser:perms-reset"),
    openExternal: (url, email) => ipcRenderer.invoke("browser:open-external", url, email),
    answerAuth: (id, user, pass, cancel) => ipcRenderer.invoke("browser:auth", { id, user, pass, cancel }),
    mute: (id) => ipcRenderer.invoke("browser:mute", id),
    find: (text, forward, next) => ipcRenderer.invoke("browser:find", { text, forward, next }),
    findStop: () => ipcRenderer.invoke("browser:find-stop"),
    onFindOpen: (cb) => { const f = () => cb(); ipcRenderer.on("browser-find-open", f); return () => ipcRenderer.off("browser-find-open", f); },
    onFindResult: (cb) => { const f = (_e, r) => cb(r); ipcRenderer.on("browser-find-result", f); return () => ipcRenderer.off("browser-find-result", f); },
    onState: (cb) => { const f = (_e, s) => cb(s); ipcRenderer.on("browser-state", f); return () => ipcRenderer.off("browser-state", f); },
    onFocusOmnibox: (cb) => { const f = () => cb(); ipcRenderer.on("browser-focus-omnibox", f); return () => ipcRenderer.off("browser-focus-omnibox", f); },
  },
  onAuthHandoff: (cb) => ipcRenderer.on("auth-handoff", (_e, t) => cb(t)),
  onOpenChat: (cb) => ipcRenderer.on("open-chat", (_e, id) => cb(id)),
  onQuickShown: (cb) => ipcRenderer.on("quick-shown", () => cb()),
  onPing: (cb) => { const f = (_e, p) => cb(p); ipcRenderer.on("ping", f); return () => ipcRenderer.off("ping", f); },
  onOpenTab: (cb) => ipcRenderer.on("open-tab", (_e, t) => cb(t)),
  viewEnter: () => ipcRenderer.invoke("view-enter"),
  viewExit: () => ipcRenderer.invoke("view-exit"),
  onOpenPings: (cb) => ipcRenderer.on("open-pings", () => cb()),
});
